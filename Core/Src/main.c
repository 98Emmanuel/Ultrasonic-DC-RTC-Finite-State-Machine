void operational_sequence(void){
	switch(current_uc_state){

	case SLEEP:

			HAL_UART_Transmit(&huart2, sleep, sizeof(sleep), 10);
			HAL_SuspendTick(); // This prevents the systick interrupts from disturbing our sleep

			HAL_PWR_EnterSLEEPMode(PWR_MAINREGULATOR_ON, PWR_SLEEPENTRY_WFI); // This is where the MCU actually sleeps - Sleeping lets some of the peripherals to continue running

			// We say that the MCU wakes up here

			SystemClock_Config();

			HAL_ResumeTick();

			//This is restarting the timers

			firstEdge = 0;

		  	HAL_TIM_IC_Start_IT(&htim2, TIM_CHANNEL_1);

		  	HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_2);

		  	HAL_TIM_Base_Start(&htim6);

		  	HAL_TIM_Base_Start(&htim7);

		  	//

			if(rtc_flag){
				rtc_flag = 0;
				current_uc_state = MEASURE;
				HAL_UART_Transmit(&huart2, wake, sizeof(wake), 10);
			}
//			current_uc_state = MEASURE;
		break;

	case MEASURE:

			measure_distance();  // this function computes the distance wherever it is

			if(distanceReady){

				distanceReady = 0;

				char msg[64];

				int len = snprintf(msg, sizeof(msg), "Distance : %.2lf\n\r", distance);

				HAL_UART_Transmit(&huart2, (uint8_t *)msg, len, HAL_MAX_DELAY);

				if(distance < 50){
			current_uc_state = STOP;
			}

			else{
				current_uc_state = MOVE;
			}
			}



		break;

	case MOVE:
			HAL_GPIO_WritePin(GPIOA, GPIO_PIN_10, GPIO_PIN_SET);
			HAL_GPIO_WritePin(GPIOA, GPIO_PIN_11, GPIO_PIN_RESET);
			__HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2, 999);

			current_uc_state = SLEEP;

		break;

	case STOP:
			HAL_GPIO_WritePin(GPIOA, GPIO_PIN_10, GPIO_PIN_SET);
			HAL_GPIO_WritePin(GPIOA, GPIO_PIN_11, GPIO_PIN_RESET);
			__HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2, 0);

			current_uc_state = SLEEP;


		break;
	}
}

void measure_distance(void){
	static uint32_t timer = 0;

	switch(current_us_state){

	case IDLE:

			__HAL_TIM_SET_COUNTER(&htim6, 0);
			HAL_GPIO_WritePin(GPIOB, GPIO_PIN_3, GPIO_PIN_RESET);
			current_us_state = TRIGGER_LOW;
			timer = __HAL_TIM_GET_COUNTER(&htim6);


		break;

	case TRIGGER_LOW:

			if(__HAL_TIM_GET_COUNTER(&htim6) - timer >= 2){
				HAL_GPIO_WritePin(GPIOB, GPIO_PIN_3, GPIO_PIN_SET);
				current_us_state = TRIGGER_HIGH;
				timer = __HAL_TIM_GET_COUNTER(&htim6);
			}


		break;

	case TRIGGER_HIGH:
			if(__HAL_TIM_GET_COUNTER(&htim6) - timer >= 10){
				HAL_GPIO_WritePin(GPIOB, GPIO_PIN_3, GPIO_PIN_RESET);
				timer = 0;
				current_us_state = WAIT_ECHO;
			}

		break; // Here according to the design that I want to make, moving to the next state should be controlled by the input capture callback


	case WAIT_ECHO:

		if(measurementReady == 1){

			measurementReady = 0;
			current_us_state = MEASUREMENT;

								}
		break;

	case MEASUREMENT:
			distance = time * 0.034f / 2.0f;

			distanceReady = 1;

			current_us_state = IDLE;

		break;
	}
}

void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim){
  /* Prevent unused argument(s) compilation warning */
  UNUSED(htim);

  /* NOTE : This function should not be modified, when the callback is needed,
            the HAL_TIM_IC_CaptureCallback could be implemented in the user file
   */
  if(htim->Instance == TIM2 && htim->Channel == HAL_TIM_ACTIVE_CHANNEL_1){

	  HAL_GPIO_TogglePin(GPIOB, GPIO_PIN_6);

	  if(firstEdge == 0){
		  IC_Value1 = HAL_TIM_ReadCapturedValue(&htim2, TIM_CHANNEL_1);
		  firstEdge = 1;
		  __HAL_TIM_SET_CAPTUREPOLARITY(&htim2, TIM_CHANNEL_1, TIM_INPUTCHANNELPOLARITY_FALLING);
	  }

	  else{
		  IC_Value2 = HAL_TIM_ReadCapturedValue(&htim2, TIM_CHANNEL_1);

		  if(IC_Value2 > IC_Value1){

			  time = IC_Value2 - IC_Value1;

		  }

		  else {
			  time = (0xFFFFFFFF - IC_Value1) + IC_Value2;
		  }
		  measurementReady = 1;
		  firstEdge = 0;
		  __HAL_TIM_SET_CAPTUREPOLARITY(&htim2, TIM_CHANNEL_1, TIM_INPUTCHANNELPOLARITY_RISING);

//		  Please never set states inside of interrupts
	  }
  }
}

